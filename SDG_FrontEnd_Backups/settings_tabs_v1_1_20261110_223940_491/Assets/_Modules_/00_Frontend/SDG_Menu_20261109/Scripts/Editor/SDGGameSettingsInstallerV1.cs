namespace SDGAdventure.FrontEnd.Editor
{
    public static class SDGGameSettingsInstallerV1
    {
        const string ScenePath = "Assets/_Modules_/00_Frontend/SDG_Menu_20261109/Scenes/SDG_StartAndMainMenu.unity";
        const string ReportName = "SDG_SettingsTabs_V1_Report.txt";
        const string Success = "SDG SETTINGS TABS V1 SUCCESS";
        static readonly Color TextColor = new Color(.88f, 1f, .96f, 1f);
        static readonly Color Mint = new Color(.30f, 1f, .83f, 1f);
        static readonly Color Dark = new Color(.014f, .15f, .14f, .95f);
        static readonly Color Stroke = new Color(.11f, .73f, .62f, .80f);
        static TMP_FontAsset font;
        static Sprite buttonSprite;

        [MenuItem("SDG Adventure/前端 UI/30 升級四頁籤設定面板")]
        public static void ApplyFromMenu()
        {
            try { Apply(); EditorUtility.DisplayDialog("SDG 設定面板", "設定面板修改完成，請在 Play Mode 驗收。", "確定"); }
            catch (Exception ex) { Debug.LogException(ex); EditorUtility.DisplayDialog("SDG 設定面板錯誤", ex.Message, "確定"); }
        }
        public static void ApplyFromBatch()
        {
            string path = Path.Combine(Directory.GetParent(Application.dataPath).FullName, ReportName);
            if (File.Exists(path)) File.Delete(path);
            Apply();
        }
        static void Apply()
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode)
                throw new InvalidOperationException("Cannot patch while Unity is playing.");
            if (AssetDatabase.LoadAssetAtPath<SceneAsset>(ScenePath) == null)
                throw new FileNotFoundException("Front-end scene not found", ScenePath);
            Scene scene = SceneManager.GetSceneByPath(ScenePath);
            bool opened = !scene.IsValid() || !scene.isLoaded;
            if (opened) scene = EditorSceneManager.OpenScene(ScenePath, OpenSceneMode.Additive);
            try
            {
                Transform canvas = null;
                foreach (GameObject go in scene.GetRootGameObjects()) if (go.name == "SDG FrontEnd Canvas") { canvas = go.transform; break; }
                if (canvas == null) throw new InvalidOperationException("SDG FrontEnd Canvas was not found. No UI changed.");
                Transform menu = canvas.Find("MENU - six actions");
                if (menu == null) throw new InvalidOperationException("MENU - six actions was not found.");
                Transform panel = menu.Find("Settings dialog");
                if (panel == null) throw new InvalidOperationException("Settings dialog was not found.");
                RectTransform panelRect = panel as RectTransform;
                Image panelImage = panel.GetComponent<Image>();
                if (panelRect == null || panelImage == null) throw new InvalidOperationException("Existing Settings dialog has no RectTransform/Image.");
                Transform heading = panel.Find("Heading");
                TextMeshProUGUI headingText = heading == null ? null : heading.GetComponent<TextMeshProUGUI>();
                if (headingText == null) throw new InvalidOperationException("Settings Heading text missing: cannot inherit its Chinese font.");
                font = headingText.font;
                if (font == null) throw new InvalidOperationException("Settings Heading has no TMP font assigned.");
                Transform oldBack = panel.Find("Close settings");
                if (oldBack != null)
                {
                    Image oldImage = oldBack.GetComponent<Image>();
                    buttonSprite = oldImage != null ? oldImage.sprite : null;
                }
                // Idempotent: replace only UI generated by THIS patch.
                Transform old = panel.Find("SDG Settings V1 Root");
                if (old != null) UnityEngine.Object.DestroyImmediate(old.gameObject);
                SDGGameSettingsPanelV1 oldComponent = panel.GetComponent<SDGGameSettingsPanelV1>();
                if (oldComponent != null) UnityEngine.Object.DestroyImmediate(oldComponent);

                // Existing back/volume/fullscreen controls are hidden, NOT deleted.
                foreach (string name in new[] { "Volume label", "Volume slider", "Fullscreen label", "Fullscreen toggle", "Close settings", "Auto save setting title", "Toggle auto save" })
                {
                    Transform t = panel.Find(name);
                    if (t != null) t.gameObject.SetActive(false);
                }
                // Preserve the panel's original location and scale; only its size changes.
                Vector2 previousPosition = panelRect.anchoredPosition;
                Vector3 previousScale = panelRect.localScale;
                Rect(panelRect, previousPosition, new Vector2(790, 540));
                panelRect.localScale = previousScale;
                // Preserve original scene image and the underlying industrial background.
                panelImage.color = new Color(.008f, .072f, .068f, .82f);
                panelImage.raycastTarget = true;
                Outline frameLine = panel.GetComponent<Outline>();
                if (frameLine == null) frameLine = panel.gameObject.AddComponent<Outline>();
                frameLine.effectColor = Mint;
                frameLine.effectDistance = new Vector2(2.5f, -2.5f);

                RectTransform root = NewRect(panel, "SDG Settings V1 Root", Vector2.zero, new Vector2(790, 540));
                MakeBox(root, "Header rail", new Vector2(0, 251), new Vector2(706, 3), Mint);
                MakeBox(root, "Footer rail", new Vector2(0, -191), new Vector2(706, 2), Stroke);
                MakeBox(root, "Left edge trace", new Vector2(-380, 0), new Vector2(3, 475), Stroke);
                MakeBox(root, "Right edge trace", new Vector2(380, 0), new Vector2(3, 475), Stroke);
                foreach (int dir in new[] { -1, 1 })
                {
                    MakeBox(root, "Top corner " + dir, new Vector2(dir * 337, 248), new Vector2(50, 5), Mint);
                    MakeBox(root, "Bottom corner " + dir, new Vector2(dir * 337, -254), new Vector2(50, 5), Mint);
                }
                Rect(headingText.rectTransform, new Vector2(0, 216), new Vector2(600, 47));
                headingText.fontSize = 32;
                headingText.alignment = TextAlignmentOptions.Center;
                headingText.text = "遊戲設定";
                headingText.color = Mint;

                SDGGameSettingsPanelV1 presenter = panel.gameObject.AddComponent<SDGGameSettingsPanelV1>();
                presenter.pages = new GameObject[4];
                presenter.tabs = new Button[4];
                presenter.tabBackgrounds = new Image[4];
                presenter.tabLabels = new TMP_Text[4];
                string[] labels = { "音效", "畫面", "操作", "遊戲" };
                for (int i = 0; i < 4; i++)
                {
                    RectTransform tab = NewRect(root, "Tab " + (i + 1), new Vector2(-282 + i * 188, 160), new Vector2(166, 43));
                    Image img = tab.gameObject.AddComponent<Image>(); img.color = Dark;
                    AddOutline(tab.gameObject, Stroke);
                    Button btn = tab.gameObject.AddComponent<Button>(); btn.targetGraphic = img;
                    presenter.tabs[i] = btn;
                    presenter.tabBackgrounds[i] = img;
                    presenter.tabLabels[i] = MakeText(tab, "Label", labels[i], Vector2.zero, new Vector2(157, 34), 22, TextAlignmentOptions.Center);
                    RectTransform page = NewRect(root, "Page " + labels[i], new Vector2(0, -16), new Vector2(720, 300));
                    Image pageBackground = MakeBox(page, "Page background", Vector2.zero, new Vector2(720, 300), new Color(.006f, .094f, .093f, .76f));
                    AddOutline(pageBackground.gameObject, new Color(.12f, .48f, .43f, .7f));
                    foreach (float y in new[] { 54f, -13f, -80f })
                        MakeBox(page, "Row separator", new Vector2(0, y), new Vector2(651, 1), new Color(.13f, .50f, .45f, .45f));
                    presenter.pages[i] = page.gameObject;
                }
                // Page 0 - real AudioListener and AudioSource categories.
                Transform audio = presenter.pages[0].transform;
                MakeRowLabel(audio, "主音量", 90);
                MakeRowLabel(audio, "背景音樂", 23);
                MakeRowLabel(audio, "遊戲音效", -44);
                presenter.master = MakeSlider(audio, "Master volume", 90, 0f, 1f);
                presenter.music = MakeSlider(audio, "Music volume", 23, 0f, 1f);
                presenter.effects = MakeSlider(audio, "Effects volume", -44, 0f, 1f);
                presenter.masterValue = MakeValue(audio, "100%", 90);
                presenter.musicValue = MakeValue(audio, "80%", 23);
                presenter.effectsValue = MakeValue(audio, "100%", -44);
                MakeText(audio, "Audio tip", "使用 AudioListener 控制主音量，依音源類別分別調整音樂與音效", new Vector2(0, -111), new Vector2(650, 28), 15, TextAlignmentOptions.Center);

                // Page 1 - fullscreen / resolution / quality.
                Transform screen = presenter.pages[1].transform;
                MakeRowLabel(screen, "全螢幕", 90);
                presenter.fullscreenButton = MakeFieldButton(screen, "Fullscreen", new Vector2(140, 90), new Vector2(274, 39), out presenter.fullscreenValue);
                MakeRowLabel(screen, "解析度", 23);
                MakeCycle(screen, "Resolution", 23, out presenter.resolutionPrev, out presenter.resolutionValue, out presenter.resolutionNext);
                MakeRowLabel(screen, "畫質", -44);
                MakeCycle(screen, "Quality", -44, out presenter.qualityPrev, out presenter.qualityValue, out presenter.qualityNext);
                MakeText(screen, "Video tip", "解析度與全螢幕會在正式遊戲套用；Unity Editor 不會強制改變 Game 視窗大小", new Vector2(0, -111), new Vector2(655, 36), 14, TextAlignmentOptions.Center);

                // Page 2 - shared FPS input, optional invert Y.
                Transform input = presenter.pages[2].transform;
                MakeRowLabel(input, "滑鼠靈敏度", 90);
                presenter.sensitivity = MakeSlider(input, "Sensitivity", 90, .1f, 10f);
                presenter.sensitivityValue = MakeValue(input, "2.0x", 90);
                MakeRowLabel(input, "反轉 Y 軸", 23);
                presenter.invertButton = MakeFieldButton(input, "Invert Y", new Vector2(140, 23), new Vector2(274, 39), out presenter.invertValue);
                MakeText(input, "Input tip A", "WASD：移動    滑鼠：視角    E：互動    F5：手動存檔", new Vector2(0, -44), new Vector2(650, 34), 17, TextAlignmentOptions.Center);
                MakeText(input, "Input tip B", "靈敏度與反轉 Y 軸會保存並在切換關卡後套用", new Vector2(0, -111), new Vector2(650, 27), 15, TextAlignmentOptions.Center);

                // Page 3 - saved-profiles auto-save preference.
                Transform game = presenter.pages[3].transform;
                MakeRowLabel(game, "自動存檔", 90);
                presenter.autoButton = MakeFieldButton(game, "Auto save", new Vector2(140, 90), new Vector2(274, 39), out presenter.autoValue);
                MakeText(game, "Auto schedule", "自動存檔時機：定期、切換關卡及遊戲結束前（依既有存檔系統）", new Vector2(0, 23), new Vector2(650, 38), 16, TextAlignmentOptions.Center);
                MakeText(game, "Auto slots", "自動存檔使用獨立欄位，不會覆蓋手動存檔", new Vector2(0, -44), new Vector2(650, 34), 17, TextAlignmentOptions.Center);
                MakeText(game, "Auto owner", "每位存檔玩家可以獨立選擇是否啟用自動存檔", new Vector2(0, -111), new Vector2(650, 30), 16, TextAlignmentOptions.Center);

                presenter.status = MakeText(root, "Settings status", "請選擇設定", new Vector2(0, -179), new Vector2(680, 26), 14, TextAlignmentOptions.Center);
                presenter.defaultsButton = MakeFooter(root, "Restore defaults", "恢復預設", new Vector2(-227, -224));
                presenter.backButton = MakeFooter(root, "Back", "返回", new Vector2(0, -224));
                presenter.applyButton = MakeFooter(root, "Apply", "套用設定", new Vector2(227, -224));

                // All active controls must be contained within the 790x540 frame.
                ValidateWithin(root, 395f, 270f);
                EditorUtility.SetDirty(presenter);
                EditorUtility.SetDirty(panelImage);
                EditorSceneManager.MarkSceneDirty(scene);
                if (!EditorSceneManager.SaveScene(scene)) throw new IOException("Unity scene save returned false.");
                AssetDatabase.SaveAssets();
                string report = Success + "\nScene=" + ScenePath + "\nPages=Audio,Video,Input,Game\n" +
                    "Original factory background/art assets=unchanged\n" +
                    "Level01-04 scene assets=unchanged\n" +
                    "Settings values=persistent PlayerPrefs\n" +
                    "Visual GameView and input integration tests=PENDING\n";
                File.WriteAllText(Path.Combine(Directory.GetParent(Application.dataPath).FullName, ReportName), report, new System.Text.UTF8Encoding(false));
                Debug.Log("[SDG Settings V1] " + report);
            }
            finally { if (opened && scene.IsValid() && scene.isLoaded) EditorSceneManager.CloseScene(scene, true); }
        }
        static RectTransform NewRect(Transform parent, string name, Vector2 pos, Vector2 size)
        {
            GameObject go = new GameObject(name, typeof(RectTransform));
            go.transform.SetParent(parent, false);
            RectTransform rt = go.GetComponent<RectTransform>();
            Rect(rt, pos, size);
            return rt;
        }
        static void Rect(RectTransform r, Vector2 pos, Vector2 size)
        {
            r.anchorMin = r.anchorMax = r.pivot = new Vector2(.5f, .5f);
            r.anchoredPosition = pos;
            r.sizeDelta = size;
            r.localScale = Vector3.one;
            r.localRotation = Quaternion.identity;
        }
        static Image MakeBox(Transform parent, string name, Vector2 pos, Vector2 size, Color color)
        {
            RectTransform rt = NewRect(parent, name, pos, size);
            Image img = rt.gameObject.AddComponent<Image>();
            img.color = color;
            img.raycastTarget = false;
            return img;
        }
        static TextMeshProUGUI MakeText(Transform parent, string name, string content, Vector2 pos, Vector2 size,
            float fontSize, TextAlignmentOptions alignment)
        {
            RectTransform rt = NewRect(parent, name, pos, size);
            TextMeshProUGUI text = rt.gameObject.AddComponent<TextMeshProUGUI>();
            text.font = font;
            text.text = content;
            text.fontSize = fontSize;
            text.fontStyle = FontStyles.Normal;
            text.color = TextColor;
            text.alignment = alignment;
            text.enableWordWrapping = false;
            text.overflowMode = TextOverflowModes.Ellipsis;
            text.raycastTarget = false;
            return text;
        }
        static void AddOutline(GameObject go, Color color)
        {
            Outline o = go.GetComponent<Outline>();
            if (o == null) o = go.AddComponent<Outline>();
            o.effectDistance = new Vector2(1f, -1f);
            o.effectColor = color;
        }
        static Button MakeFieldButton(Transform parent, string name, Vector2 pos, Vector2 size, out TMP_Text value)
        {
            RectTransform rt = NewRect(parent, name, pos, size);
            Image img = rt.gameObject.AddComponent<Image>(); img.color = Dark;
            AddOutline(rt.gameObject, Stroke);
            Button b = rt.gameObject.AddComponent<Button>(); b.targetGraphic = img;
            value = MakeText(rt, "Value", "--", Vector2.zero, new Vector2(size.x - 24, size.y - 8), 19, TextAlignmentOptions.Center);
            return b;
        }
        static void MakeCycle(Transform parent, string label, float y, out Button prev, out TMP_Text value, out Button next)
        {
            TMP_Text ignored;
            prev = MakeFieldButton(parent, label + " prev", new Vector2(25, y), new Vector2(46, 39), out ignored);
            ignored.text = "◀";
            RectTransform valRect = NewRect(parent, label + " current", new Vector2(140, y), new Vector2(169, 39));
            Image img = valRect.gameObject.AddComponent<Image>(); img.color = Dark;
            AddOutline(valRect.gameObject, Stroke);
            value = MakeText(valRect, "Value", "--", Vector2.zero, new Vector2(163, 32), 18, TextAlignmentOptions.Center);
            next = MakeFieldButton(parent, label + " next", new Vector2(255, y), new Vector2(46, 39), out ignored);
            ignored.text = "▶";
        }
        static void MakeRowLabel(Transform parent, string name, float y)
        {
            MakeText(parent, name + " label", name, new Vector2(-235, y), new Vector2(210, 39), 20, TextAlignmentOptions.Left);
        }
        static TMP_Text MakeValue(Transform parent, string value, float y)
        {
            return MakeText(parent, "Reading " + y, value, new Vector2(311, y), new Vector2(68, 30), 16, TextAlignmentOptions.Center);
        }
        static Slider MakeSlider(Transform parent, string name, float y, float min, float max)
        {
            RectTransform rt = NewRect(parent, name, new Vector2(143, y), new Vector2(257, 42));
            Slider slider = rt.gameObject.AddComponent<Slider>();
            slider.direction = Slider.Direction.LeftToRight;
            slider.minValue = min;
            slider.maxValue = max;
            slider.wholeNumbers = false;
            Image track = MakeBox(rt, "Track", Vector2.zero, new Vector2(242, 12), new Color(.04f, .27f, .24f, 1f));
            track.raycastTarget = true; // Clicking the rail also reaches the Slider component.
            RectTransform fillArea = NewRect(rt, "Fill Area", Vector2.zero, new Vector2(242, 12));
            Image fill = MakeBox(fillArea, "Fill", Vector2.zero, new Vector2(242, 12), Mint);
            // A zero-offset stretched Fill is REQUIRED for Slider.UpdateVisuals to resize correctly.
            fill.rectTransform.anchorMin = Vector2.zero;
            fill.rectTransform.anchorMax = Vector2.one;
            fill.rectTransform.offsetMin = Vector2.zero;
            fill.rectTransform.offsetMax = Vector2.zero;
            RectTransform handleArea = NewRect(rt, "Handle Slide Area", Vector2.zero, new Vector2(242, 34));
            Image handle = MakeBox(handleArea, "Handle", Vector2.zero, new Vector2(12, 30), new Color(.8f, 1f, .92f, 1f));
            handle.raycastTarget = true;
            slider.fillRect = fill.rectTransform;
            slider.handleRect = handle.rectTransform;
            slider.targetGraphic = handle;
            slider.value = min;
            return slider;
        }
        static Button MakeFooter(Transform parent, string name, string text, Vector2 pos)
        {
            RectTransform rt = NewRect(parent, name, pos, new Vector2(190, 48));
            Image image = rt.gameObject.AddComponent<Image>();
            image.sprite = buttonSprite;
            image.color = buttonSprite != null ? Color.white : Dark;
            image.preserveAspect = buttonSprite != null;
            AddOutline(rt.gameObject, Stroke);
            Button button = rt.gameObject.AddComponent<Button>(); button.targetGraphic = image;
            MakeText(rt, "Label", text, Vector2.zero, new Vector2(168, 31), 19, TextAlignmentOptions.Center);
            return button;
        }
        static void ValidateWithin(RectTransform root, float maxX, float maxY)
        {
            foreach (RectTransform child in root.GetComponentsInChildren<RectTransform>(true))
            {
                if (child == root) continue;
                // Every created element has center anchors; summing local positions yields panel-local bounds.
                Vector2 offset = Vector2.zero;
                Transform cursor = child;
                while (cursor != null && cursor != root)
                {
                    offset += (Vector2)((RectTransform)cursor).anchoredPosition;
                    cursor = cursor.parent;
                }
                if (Mathf.Abs(offset.x) + child.rect.width * .5f > maxX + 1f ||
                    Mathf.Abs(offset.y) + child.rect.height * .5f > maxY + 1f)
                    throw new InvalidOperationException("UI element outside settings panel: " + child.name);
            }
        }
    }
